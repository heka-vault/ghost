#!/usr/bin/env python
"""Write Parakeet's mel filterbank table into ``crates/ghost-infer/src/parakeet_fbanks.rs``.

``onnx_asr`` ships the table NeMo exported with the model (``preprocessors/data/fbanks.npz``,
member ``nemo128``, float32, 257 bins by 128 filters) and its NumPy preprocessor multiplies
the power spectrum by it. The table was computed in float32 and is up to 8 ulps off the
Slaney formula evaluated in float64, and the int8 model flips a comma or a capital on a
feature difference that small, so the Rust port carries the same numbers: the non-zero
weights (about two per bin) as ``(bin, filter, bits)``. Run through the oracle's environment
(``tools/oracle``)::

    uv run --project tools/oracle python -I scripts/fixtures/nemo_fbanks.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np


def main() -> None:
    import onnx_asr.preprocessors

    with np.load(Path(onnx_asr.preprocessors.__file__).parent / "data" / "fbanks.npz") as data:
        table = data["nemo128"]
    assert table.dtype == np.float32 and table.shape == (257, 128), (table.dtype, table.shape)
    bins, mels = np.nonzero(table)
    out = (
        Path(sys.argv[1])
        if len(sys.argv) > 1
        else (
            Path(__file__).resolve().parents[2]
            / "crates"
            / "ghost-infer"
            / "src"
            / "parakeet_fbanks.rs"
        )
    )
    lines = [
        "//! Parakeet's mel filterbank (`nemo128`), the float32 table NeMo exported with the model",
        "//! and `onnx_asr` ships in `preprocessors/data/fbanks.npz`: the non-zero weights of the",
        "//! 257-bin by 128-filter matrix as `(bin, filter, f32 bits)`, in row order. Generated by",
        "//! `scripts/fixtures/nemo_fbanks.py`; the parity test",
        "//! `filterbanks_match_the_python_tables`",
        "//! checks it against the file.",
        "",
        "pub const BINS: usize = 257;",
        "pub const FILTERS: usize = 128;",
        "",
        "/// `(bin, filter, bits)` for every non-zero weight, bins ascending.",
        "pub const WEIGHTS: &[(u16, u8, u32)] = &[",
    ]
    for b, m in zip(bins.tolist(), mels.tolist(), strict=True):
        bits = int(np.asarray(table[b, m], dtype=np.float32).view(np.uint32))
        lines.append(f"    ({b}, {m}, 0x{bits:08x}),")
    lines.append("];")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(bins)} non-zero weights -> {out}")


if __name__ == "__main__":
    main()
